def cmd_selftest(args) -> int:  # noqa: ARG001
    """Assert core search behaviours.  Exits non-zero on the first failure.

    Ported from niagara-research (N4 kit tool): the N4 version scanned the REAL
    corpus for a term ("BStatus") known to occur in specific N4 blocks. That
    made the selftest depend on corpus content that does not exist here — a
    fresh N5 corpus has no blocks yet, and even once it does, pinning a
    selftest to one target's vocabulary is fragile. This port builds a small
    synthetic fixture corpus in a temp dir and points REPO_ROOT/CATALOG_PATH
    at it for the duration of the assertions, so the selftest is hermetic and
    passes regardless of what has actually been written into the corpus.
    """
    global REPO_ROOT, CATALOG_PATH
    errors: list[str] = []

    _orig_repo_root, _orig_catalog_path = REPO_ROOT, CATALOG_PATH
    _tmp = tempfile.TemporaryDirectory()
    try:
        tmp_root = Path(_tmp.name)
        (tmp_root / "niagara5-block1.md").write_text(
            "# Block 1: BStatus overridden\n\n"
            "Some text about a point's BStatus overridden by an operator.\n",
            encoding="utf-8",
        )
        (tmp_root / "niagara5-block2.md").write_text(
            "# Block 2: unrelated topic\n\nContent with nothing in common.\n",
            encoding="utf-8",
        )
        (tmp_root / "CATALOG.md").write_text(
            "| Block | File | Title |\n"
            "|-------|------|-------|\n"
            "| 1 | [niagara5-block1.md](niagara5-block1.md) | BStatus overridden |\n"
            "| 2 | [niagara5-block2.md](niagara5-block2.md) | unrelated topic |\n",
            encoding="utf-8",
        )
        REPO_ROOT = tmp_root
        CATALOG_PATH = tmp_root / "CATALOG.md"

        _run_selftest_assertions(errors)
    finally:
        REPO_ROOT, CATALOG_PATH = _orig_repo_root, _orig_catalog_path
        _tmp.cleanup()

    if errors:
        for e in errors:
            print(f"  FAIL  {e}", file=sys.stderr)
        return 1
    print("selftest: all assertions passed.")
    return 0


def _run_selftest_assertions(errors: list[str]) -> None:
    # --- Test 1: single-word term returns at least one block ---------------
    terms1 = textsearch.parse_query("BStatus")
    hits1 = sum(
        1 for _, path in corpus_targets("blocks")
        if textsearch.file_matches(terms1, path.read_text(encoding="utf-8").lower(), "or")
    )
    if hits1 == 0:
        errors.append("'BStatus' (single-word OR) → 0 blocks; expected > 0")
    else:
        print(f"  PASS  single-word 'BStatus' → {hits1} block(s)")

    # --- Test 2: two-word query (OR) whose words co-occur returns > 0 ------
    terms2 = textsearch.parse_query("BStatus overridden")
    hits2 = sum(
        1 for _, path in corpus_targets("blocks")
        if textsearch.file_matches(terms2, path.read_text(encoding="utf-8").lower(), "or")
    )
    if hits2 == 0:
        errors.append("'BStatus overridden' (OR) → 0 blocks; expected > 0")
    else:
        print(f"  PASS  two-word OR 'BStatus overridden' → {hits2} block(s)")

    # --- Test 3: two-word AND also returns > 0 (both words appear in B6+) --
    hits3 = sum(
        1 for _, path in corpus_targets("blocks")
        if textsearch.file_matches(terms2, path.read_text(encoding="utf-8").lower(), "and")
    )
    if hits3 == 0:
        errors.append("'BStatus overridden' (AND) → 0 blocks; expected > 0")
    else:
        print(f"  PASS  two-word AND 'BStatus overridden' → {hits3} block(s)")

    # --- Test 4: ranking — higher-scoring block comes first ----------------
    # Synthetic in-memory check (independent of corpus content).
    terms_r = textsearch.parse_query("alarm fault")
    text_high = "alarm fault alarm fault"   # both terms, 4 total occurrences
    text_low  = "alarm"                     # one term, 1 occurrence
    s_high = textsearch.score(terms_r, text_high)
    s_low  = textsearch.score(terms_r, text_low)
    if s_high <= s_low:
        errors.append(
            f"ranking: score({text_high!r}) = {s_high} should be > "
            f"score({text_low!r}) = {s_low}"
        )
    else:
        print(f"  PASS  ranking: score(high)={s_high} > score(low)={s_low}")

    # --- Test 5: semantic ranking puts a status/BStatus block in top-5 -----
    # 'point health fault override status' should surface status-related blocks.
    catalog_st = load_catalog()
    semantic5 = _semantic_ranked("point health fault override status", iter_block_files())
    top5_titles = [
        title_for(lbl, catalog_st, p).lower()
        for _, lbl, p in semantic5[:5]
    ]
    if not any("status" in t or "bstatus" in t for t in top5_titles):
        top5_ids = [display_id(lbl) for _, lbl, _ in semantic5[:5]]
        errors.append(
            f"semantic 'point health fault override status': top-5 {top5_ids} "
            f"titles {top5_titles!r} — expected one mentioning status/BStatus"
        )
    else:
        top5_ids = [display_id(lbl) for _, lbl, _ in semantic5[:5]]
        print(f"  PASS  semantic ranking 'status' query → top-5 {top5_ids}")


