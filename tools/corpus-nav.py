#!/usr/bin/env python3
"""
corpus-nav.py — Navigate the niagara5-research knowledge corpus.

Ported from niagara-research (N4 kit tool) for the niagara5-research corpus.
Adaptation from the N4 original: block filenames/H1s are English
`niagara5-block<N>.md` ("Block N") instead of Spanish
`niagara-mental-model-bloque<N>.md` ("Bloque N"); there is no consolidated
"1-3" snapshot file (N5 blocks are written one-per-file from the start); and
cross-references only use the English `[Block N]` / `[BN]` forms.

Python 3 stdlib ONLY. Deterministic, sorted output. No external deps, no DB.

The corpus (all paths relative to the repo root, resolved from this script):
  - Blocks:  niagara5-block<N>.md  (N is a GLOBAL block number with possible
             historical gaps), plus niagara5-block-test-infrastructure.md
             (label "TI").
  - CATALOG.md — AUTOGENERATED authoritative index. Each row is
             `| <label> | [file](file) | <title> |`. Source of truth for the
             block <-> title map. This tool NEVER edits it.
  - docs/*.md    — synthesis guides.
  - retros/*.md  — retrospectives.
  - RESEARCH-STATE-<focus>.md — per-focus state files.

Subcommands:
  find <query>        full-text (case-insensitive substring) search
  grep <regex>        regex search (re module)
  show <N>            H1 + section outline + Connections of block B<N>
  list                all blocks as `B<N> · <title>` (from CATALOG.md)
  by-marker <marker>  blocks containing an evidence marker (INFER, CERT-hw, ...)
  by-focus <focus>    blocks belonging to a focus (see heuristic below)
  connections <N>     forward + reverse block links for B<N>
  stats               corpus totals + marker counts

Run `corpus-nav.py <cmd> -h` for per-command flags.
"""

from __future__ import annotations

import argparse
import math
import re
import sys
import tempfile
from pathlib import Path

# ---------------------------------------------------------------------------
# Shared search core (tools/lib/textsearch.py).
# Insert lib/ onto sys.path so the import works regardless of cwd.
# ---------------------------------------------------------------------------
sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import textsearch  # noqa: E402 (must follow sys.path mutation)

# ---------------------------------------------------------------------------
# Repository layout — always relative to this script's location.
# tools/corpus-nav.py  ->  repo root is the parent of tools/.
# ---------------------------------------------------------------------------
REPO_ROOT = Path(__file__).resolve().parent.parent
CATALOG_PATH = REPO_ROOT / "CATALOG.md"
DOCS_DIR = REPO_ROOT / "docs"
RETROS_DIR = REPO_ROOT / "retros"

# Snapshot block files excluded from the active corpus (mirrors gen-catalog.py).
# None in the N5 corpus yet; kept as a set so the mechanism still works if one
# is ever added.
SNAPSHOTS: set[str] = set()

# ---------------------------------------------------------------------------
# Evidence markers: [CERT], [CERT-hw], [CERT-live], [CERT-doc], [CERT-web],
# [INFER], and combined forms like [CERT-doc/INFER]. A bracket token may hold
# several slash-separated components; each component is one marker instance.
# ---------------------------------------------------------------------------
_MARKER_TOKEN_RE = re.compile(r"\[((?:CERT|INFER)[\w/-]*)\]")

# ---------------------------------------------------------------------------
# Block references used inside prose / Connections. N5 corpus artifacts are
# English-only (repo-wide contract), so only the English forms are matched:
# [Block N] (dominant) and [BN]. The N4 tool's Spanish "Bloque"/"bloqueN"
# forms do not apply here.
# ---------------------------------------------------------------------------
_REF_RE = re.compile(
    r"\[Block\s+#?(\d+)\]"  # [Block 18]
    r"|\[B(\d+)\]",          # [B722]
    re.IGNORECASE,
)


# ---------------------------------------------------------------------------
# Block file discovery + numbering (robust to historical gaps: nothing here
# assumes N is contiguous — we only ever use the labels we actually find).
# ---------------------------------------------------------------------------
_BLOCK_NUM_RE = re.compile(r"^niagara5-block(\d+)\.md$")


def block_label_for_file(name: str) -> str | None:
    """Return the block label for a corpus filename, or None if not a block.

    Numeric blocks -> str(N); TI file -> "TI".
    """
    if name in SNAPSHOTS:
        return None
    if name == "niagara5-block-test-infrastructure.md":
        return "TI"
    m = _BLOCK_NUM_RE.match(name)
    if m:
        return str(int(m.group(1)))
    return None


def label_sort_key(label: str) -> tuple[int, int]:
    """Deterministic ordering: numeric by value, TI last."""
    if label == "TI":
        return (2, 0)
    return (1, int(label))


def display_id(label: str) -> str:
    """Human id used throughout output: B720, B1-3, BTI."""
    return f"B{label}"


def iter_block_files() -> list[tuple[str, Path]]:
    """All active block files as (label, path), sorted deterministically."""
    out: list[tuple[str, Path]] = []
    for path in REPO_ROOT.glob("niagara5-block*.md"):
        label = block_label_for_file(path.name)
        if label is not None:
            out.append((label, path))
    out.sort(key=lambda t: label_sort_key(t[0]))
    return out


def iter_dir_files(directory: Path) -> list[Path]:
    """Sorted *.md files directly under a directory (docs/, retros/)."""
    if not directory.is_dir():
        return []
    return sorted(directory.glob("*.md"))


# ---------------------------------------------------------------------------
# CATALOG.md parsing — source of truth for label -> title.
# Rows look like: `| 720 | [file](file) | title |`
# ---------------------------------------------------------------------------
_CATALOG_ROW_RE = re.compile(r"^\|\s*([^|]+?)\s*\|\s*\[[^\]]+\]\([^)]+\)\s*\|\s*(.*?)\s*\|\s*$")


def load_catalog() -> dict[str, str]:
    """Parse CATALOG.md into {label: title}. Empty dict if file is missing."""
    titles: dict[str, str] = {}
    if not CATALOG_PATH.is_file():
        return titles
    for line in CATALOG_PATH.read_text(encoding="utf-8").splitlines():
        m = _CATALOG_ROW_RE.match(line)
        if not m:
            continue
        label, title = m.group(1).strip(), m.group(2).strip()
        # Skip the header separator / header row.
        if label in ("Block", "--------") or set(label) <= {"-"}:
            continue
        titles[label] = title
    return titles


# ---------------------------------------------------------------------------
# Per-block text helpers
# ---------------------------------------------------------------------------
def read_h1(path: Path) -> str:
    """First H1 line ('# ...') from a file, stripped of the leading '# '."""
    try:
        with path.open(encoding="utf-8") as f:
            for line in f:
                s = line.strip()
                if s.startswith("# "):
                    return s[2:].strip()
    except OSError:
        pass
    return ""


def title_for(label: str, catalog: dict[str, str], path: Path) -> str:
    """CATALOG title if present, else the block's own H1, else '(no title)'."""
    return catalog.get(label) or read_h1(path) or "(no title)"


def extract_section(path: Path, header_names: tuple[str, ...]) -> list[str]:
    """Return the lines of a '## <name>' section (until the next '## ' heading).

    Matching on the header text is case-insensitive; header_names are the
    accepted heading titles (e.g. ('Connections',)).
    """
    wanted = {h.lower() for h in header_names}
    lines = path.read_text(encoding="utf-8").splitlines()
    out: list[str] = []
    capturing = False
    for line in lines:
        if line.startswith("## "):
            if capturing:
                break  # reached the next section
            capturing = line[3:].strip().lower() in wanted
            continue
        if capturing:
            out.append(line)
    return out


def refs_in_text(text: str) -> set[int]:
    """All block numbers referenced in a chunk of text."""
    nums: set[int] = set()
    for m in _REF_RE.finditer(text):
        for g in m.groups():
            if g:
                nums.add(int(g))
    return nums


# ---------------------------------------------------------------------------
# Focus membership (by-focus / list --focus)
#
# Heuristic (two complementary signals, unioned):
#   1) Block-header tag: a block whose body contains `Focus: **<focus>**`
#      declares itself part of that focus. This is the primary, authoritative
#      signal (used by ~71 blocks that carry the tag).
#   2) RESEARCH-STATE-<focus>.md citations: block numbers explicitly referenced
#      in the focus state file ([Block N] / [BN] / bloqueN). This recovers the
#      blocks a focus owns even when the block header predates the tag
#      convention or uses different wording.
# The union is returned as sorted labels. This is a best-effort mapping; the
# corpus does not carry a single machine-readable focus field per block.
# ---------------------------------------------------------------------------
def blocks_for_focus(focus: str) -> list[str]:
    focus_l = focus.lower()
    header_re = re.compile(r"Focus:\s*\*\*" + re.escape(focus) + r"\*\*", re.IGNORECASE)
    found: set[str] = set()

    # Signal 1: block-header Focus tag.
    for label, path in iter_block_files():
        try:
            head = path.read_text(encoding="utf-8")[:2000]
        except OSError:
            continue
        if header_re.search(head):
            found.add(label)

    # Signal 2: RESEARCH-STATE-<focus>.md citations.
    state = REPO_ROOT / f"RESEARCH-STATE-{focus}.md"
    if state.is_file():
        cited = refs_in_text(state.read_text(encoding="utf-8"))
        for n in cited:
            found.add(str(n))

    return sorted(found, key=label_sort_key)


def available_focuses() -> list[str]:
    out = []
    for p in sorted(REPO_ROOT.glob("RESEARCH-STATE-*.md")):
        out.append(p.name[len("RESEARCH-STATE-"):-len(".md")])
    return out


# ---------------------------------------------------------------------------
# Search corpus selection
# ---------------------------------------------------------------------------
def corpus_targets(scope: str) -> list[tuple[str, Path]]:
    """Return (display, path) pairs for the requested scope.

    For blocks, display is 'B<label>'; for docs/retros it is the relative path.
    """
    targets: list[tuple[str, Path]] = []
    if scope in ("blocks", "all"):
        for label, path in iter_block_files():
            targets.append((display_id(label), path))
    if scope in ("docs", "all"):
        for path in iter_dir_files(DOCS_DIR):
            targets.append((str(path.relative_to(REPO_ROOT)), path))
    if scope in ("retros", "all"):
        for path in iter_dir_files(RETROS_DIR):
            targets.append((str(path.relative_to(REPO_ROOT)), path))
    return targets


def run_search(pattern, scope: str, limit: int, catalog: dict[str, str]) -> int:
    """Shared engine for find/grep. `pattern` has a .search(str) method.

    Prints, grouped per file: a header line, then matching 'lineno: text'
    lines. `limit` caps the TOTAL number of matching lines printed.
    """
    shown = 0
    printed_any = False
    for display, path in corpus_targets(scope):
        if shown >= limit:
            break
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except OSError:
            continue
        matches = [(i + 1, ln) for i, ln in enumerate(lines) if pattern.search(ln)]
        if not matches:
            continue
        # Header: 'B<N> · <title>' for blocks, '<relpath> · <H1>' otherwise.
        if display.startswith("B"):
            label = display[1:]
            header = f"{display} · {title_for(label, catalog, path)}"
        else:
            header = f"{display} · {read_h1(path)}".rstrip(" ·")
        if printed_any:
            print()
        print(header)
        printed_any = True
        for lineno, text in matches:
            if shown >= limit:
                print(f"    ... (limit {limit} reached; use --limit to see more)")
                break
            print(f"  {lineno:>6}: {text.strip()}")
            shown += 1
    if not printed_any:
        print("No matches.")
        return 1
    return 0


# ---------------------------------------------------------------------------
# TF-IDF semantic ranking (lexical-semantic; stdlib pure — no torch/sklearn)
#
# Tokenization: lowercase, split on non-alphanumeric, drop tokens < 3 chars
# and a combined English+Spanish stopword set.  IDF smoothing:
#   idf(t) = log(N / (1 + df(t))) + 1
# Cosine similarity on the resulting sparse vectors.
# ---------------------------------------------------------------------------
_TFIDF_SPLIT_RE = re.compile(r"[^a-z0-9]+")

_STOPWORDS: frozenset[str] = frozenset({
    # English
    "the", "and", "for", "with", "this", "that", "are", "was", "were",
    "has", "have", "had", "not", "but", "from", "into", "its", "can",
    "will", "also", "all", "any", "one", "each", "when", "then", "than",
    "they", "them", "their", "there", "been", "being", "out", "more",
    "over", "such", "how", "use", "used", "using", "per", "via", "get",
    "set", "new", "add", "may", "see", "two", "own", "now", "well",
    # Spanish
    "que", "los", "las", "del", "por", "una", "con", "para", "como",
    "sus", "son", "sin", "mas", "hay", "ser", "est", "una",
})


def _tokenize_for_tfidf(text: str) -> list[str]:
    """Lowercase, split on non-alphanumeric, drop tokens < 3 chars and stopwords."""
    return [
        t for t in _TFIDF_SPLIT_RE.split(text.lower())
        if len(t) >= 3 and t not in _STOPWORDS
    ]


def _build_tfidf_index(
    blocks: list[tuple[str, Path]],
) -> tuple[list[tuple[str, Path, dict[str, float], float]], dict[str, float]]:
    """Build per-block TF-IDF sparse vectors.

    Returns (index, idf_table) where:
      index — list of (label, path, tfidf_sparse_dict, L2_norm)
      idf_table — {term: idf_weight} for constructing the query vector
    """
    all_tokens: list[list[str]] = []
    for _, path in blocks:
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            text = ""
        all_tokens.append(_tokenize_for_tfidf(text))

    n_docs = len(blocks)

    # Document frequency.
    df: dict[str, int] = {}
    for tokens in all_tokens:
        for t in set(tokens):
            df[t] = df.get(t, 0) + 1

    # IDF with smoothing.
    idf: dict[str, float] = {
        t: math.log(n_docs / (1 + cnt)) + 1.0
        for t, cnt in df.items()
    }

    # Per-block sparse TF-IDF vector + L2 norm.
    index: list[tuple[str, Path, dict[str, float], float]] = []
    for (label, path), tokens in zip(blocks, all_tokens):
        tf: dict[str, int] = {}
        for t in tokens:
            tf[t] = tf.get(t, 0) + 1
        tfidf: dict[str, float] = {t: cnt * idf[t] for t, cnt in tf.items()}
        norm_sq = sum(v * v for v in tfidf.values())
        norm = math.sqrt(norm_sq) if norm_sq > 0 else 0.0
        index.append((label, path, tfidf, norm))

    return index, idf


def _semantic_ranked(
    query: str,
    blocks: list[tuple[str, Path]],
) -> list[tuple[float, str, Path]]:
    """Return (cosine_sim, label, path) sorted desc; skips zero-score blocks."""
    query_tokens = _tokenize_for_tfidf(query)
    if not query_tokens:
        return []

    index, idf = _build_tfidf_index(blocks)

    qtf: dict[str, int] = {}
    for t in query_tokens:
        qtf[t] = qtf.get(t, 0) + 1
    qtfidf: dict[str, float] = {t: cnt * idf.get(t, 0.0) for t, cnt in qtf.items()}
    qnorm_sq = sum(v * v for v in qtfidf.values())
    qnorm = math.sqrt(qnorm_sq) if qnorm_sq > 0 else 0.0

    if qnorm == 0.0:
        return []

    scored: list[tuple[float, str, Path]] = []
    for label, path, tfidf, norm in index:
        if norm == 0.0:
            continue
        dot = sum(qtfidf[t] * tfidf.get(t, 0.0) for t in qtfidf if t in tfidf)
        if dot == 0.0:
            continue
        sim = dot / (qnorm * norm)
        scored.append((sim, label, path))

    scored.sort(key=lambda t: -t[0])
    return scored


def _best_snippet(lines: list[str], query_terms: set[str]) -> str:
    """Return the line with the highest count of query-term substring matches."""
    best = ""
    best_count = -1
    for line in lines:
        line_lower = line.lower()
        count = sum(1 for t in query_terms if t in line_lower)
        if count > best_count:
            best_count = count
            best = line.strip()
    return best


def cmd_semantic(args) -> int:
    """Rank blocks by TF-IDF cosine similarity to the query, best first.

    Note: this is TF-IDF lexical-semantic ranking; true neural embeddings
    would need an external model/dependency (out of scope, keeps the tool
    stdlib-pure).
    """
    catalog = load_catalog()
    query_terms_set = set(textsearch.parse_query(args.query))  # for snippet
    blocks = iter_block_files()
    scored = _semantic_ranked(args.query, blocks)

    if not scored:
        print("No semantic matches.")
        print("(Note: absence of semantic matches is not proof of absence.)")
        return 1

    for sim, label, path in scored[: args.limit]:
        title = title_for(label, catalog, path)
        print(f"{display_id(label)} · {title}   (score {sim:.3f})")
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except OSError:
            lines = []
        snippet = _best_snippet(lines, query_terms_set)
        if snippet:
            if len(snippet) > 120:
                snippet = snippet[:117] + "..."
            print(f"  » {snippet}")

    return 0


