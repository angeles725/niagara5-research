def cmd_find(args) -> int:
    """Full-text search with tokenized matching and relevance ranking.

    Tokenises *args.query* into terms so that multi-word queries match files
    where the words appear *anywhere* (not necessarily as a contiguous phrase).
    Results are sorted by relevance score (most-relevant first) before printing.

    Mode flags (--and / --or) control the file-level matching:
        --or  (default): a block is shown if ANY term is present in it.
        --and:           a block is shown only if ALL terms are present.

    Single-word queries behave identically to the original implementation.
    """
    catalog = load_catalog()
    terms = textsearch.parse_query(args.query)
    mode = "and" if getattr(args, "mode_and", False) else "or"

    if not terms:
        print("No matches.")
        return 1

    # Collect (score, display, path, matching_lines) for every matching block.
    ranked: list[tuple[int, str, Path, list[tuple[int, str]]]] = []
    for display, path in corpus_targets(args.scope):
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except OSError:
            continue
        text_lower = "\n".join(lines).lower()
        if not textsearch.file_matches(terms, text_lower, mode):
            continue
        s = textsearch.score(terms, text_lower)
        hits = [
            (i + 1, ln)
            for i, ln in enumerate(lines)
            if textsearch.line_hits(terms, ln.lower())
        ]
        ranked.append((s, display, path, hits))

    if not ranked:
        print("No matches.")
        return 1

    # Sort by score descending so the most-relevant blocks appear first.
    ranked.sort(key=lambda t: -t[0])

    shown = 0
    printed_any = False
    for _score, display, path, hits in ranked:
        if shown >= args.limit:
            break
        if display.startswith("B"):
            label = display[1:]
            header = f"{display} · {title_for(label, catalog, path)}"
        else:
            header = f"{display} · {read_h1(path)}".rstrip(" ·")
        if printed_any:
            print()
        print(header)
        printed_any = True
        for lineno, text in hits:
            if shown >= args.limit:
                print(f"    ... (limit {args.limit} reached; use --limit to see more)")
                break
            print(f"  {lineno:>6}: {text.strip()}")
            shown += 1

    return 0


def cmd_grep(args) -> int:
    catalog = load_catalog()
    try:
        pattern = re.compile(args.regex, re.IGNORECASE)
    except re.error as e:
        print(f"Invalid regex: {e}", file=sys.stderr)
        return 2
    return run_search(pattern, args.scope, args.limit, catalog)


def _find_block_path(n: int) -> tuple[str, Path] | None:
    """Locate a numeric block file by its number."""
    for label, path in iter_block_files():
        if label not in ("1-3", "TI") and int(label) == n:
            return label, path
    return None


def cmd_show(args) -> int:
    catalog = load_catalog()
    found = _find_block_path(args.n)
    if not found:
        print(f"Block B{args.n} not found.", file=sys.stderr)
        return 1
    label, path = found

    print(f"{display_id(label)} · {title_for(label, catalog, path)}")
    print(f"  file: {path.relative_to(REPO_ROOT)}")

    # Section outline: every ## / ### heading (H1 already printed above).
    print("\n## Outline")
    any_heading = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("### "):
            print(f"    - {line[4:].strip()}")
            any_heading = True
        elif line.startswith("## "):
            print(f"  - {line[3:].strip()}")
            any_heading = True
    if not any_heading:
        print("  (no sub-headings)")

    # Connections section verbatim.
    print("\n## Connections")
    conn = extract_section(path, ("Connections", "Conexiones"))
    conn_text = "\n".join(conn).strip()
    if conn_text:
        for line in conn_text.splitlines():
            print(f"  {line}")
    else:
        print("  (no Connections section)")
    return 0


def cmd_list(args) -> int:
    catalog = load_catalog()
    focus_set = None
    if args.focus:
        focus_set = set(blocks_for_focus(args.focus))
        if not focus_set:
            print(f"No blocks found for focus '{args.focus}'.", file=sys.stderr)
            return 1
    count = 0
    for label, path in iter_block_files():
        if focus_set is not None and label not in focus_set:
            continue
        print(f"{display_id(label)} · {title_for(label, catalog, path)}")
        count += 1
    print(f"\nTotal: {count} block(s)" + (f" in focus '{args.focus}'" if args.focus else ""))
    return 0


def _marker_components(text: str) -> list[str]:
    """All marker components in text, expanding combined [A/B] tokens."""
    comps: list[str] = []
    for m in _MARKER_TOKEN_RE.finditer(text):
        for part in m.group(1).split("/"):
            part = part.strip()
            if part:
                comps.append(part)
    return comps


def cmd_by_marker(args) -> int:
    catalog = load_catalog()
    marker = args.marker.strip().strip("[]").lower()
    rows: list[tuple[str, int, Path]] = []
    for label, path in iter_block_files():
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        cnt = sum(1 for c in _marker_components(text) if c.lower() == marker)
        if cnt:
            rows.append((label, cnt, path))
    if not rows:
        print(f"No blocks contain marker [{args.marker}].")
        return 1
    for label, cnt, path in rows:
        print(f"{display_id(label)} · {cnt:>4} · {title_for(label, catalog, path)}")
    total = sum(c for _, c, _ in rows)
    print(f"\n{len(rows)} block(s), {total} occurrence(s) of [{args.marker}].")
    return 0


def cmd_by_focus(args) -> int:
    catalog = load_catalog()
    labels = blocks_for_focus(args.focus)
    if not labels:
        avail = ", ".join(available_focuses())
        print(f"No blocks found for focus '{args.focus}'.", file=sys.stderr)
        print(f"Known focuses: {avail}", file=sys.stderr)
        return 1
    by_file = {lbl: path for lbl, path in iter_block_files()}
    for label in labels:
        path = by_file.get(label)
        title = title_for(label, catalog, path) if path else "(block file not present)"
        print(f"{display_id(label)} · {title}")
    print(f"\nTotal: {len(labels)} block(s) in focus '{args.focus}'.")
    return 0


def cmd_connections(args) -> int:
    catalog = load_catalog()
    found = _find_block_path(args.n)
    if not found:
        print(f"Block B{args.n} not found.", file=sys.stderr)
        return 1
    label, path = found
    by_file = {lbl: p for lbl, p in iter_block_files()}

    print(f"{display_id(label)} · {title_for(label, catalog, path)}")

    # Forward: references inside this block's ## Connections section.
    print("\n## Forward links (this block -> others, from its Connections section)")
    conn = "\n".join(extract_section(path, ("Connections", "Conexiones")))
    fwd = sorted(n for n in refs_in_text(conn) if n != args.n)
    if fwd:
        for n in fwd:
            p = by_file.get(str(n))
            title = title_for(str(n), catalog, p) if p else "(not in corpus)"
            print(f"  B{n} · {title}")
    else:
        print("  (none)")

    # Reverse: any block anywhere that references B<N>.
    print(f"\n## Reverse links (other blocks -> B{args.n}, whole-corpus scan)")
    rev_rows: list[tuple[str, Path]] = []
    for lbl, p in iter_block_files():
        if lbl not in ("1-3", "TI") and int(lbl) == args.n:
            continue
        try:
            text = p.read_text(encoding="utf-8")
        except OSError:
            continue
        if args.n in refs_in_text(text):
            rev_rows.append((lbl, p))
    rev_rows.sort(key=lambda t: label_sort_key(t[0]))
    if rev_rows:
        for lbl, p in rev_rows:
            print(f"  {display_id(lbl)} · {title_for(lbl, catalog, p)}")
    else:
        print("  (none)")
    return 0


def cmd_stats(args) -> int:
    blocks = iter_block_files()
    docs = iter_dir_files(DOCS_DIR)
    retros = iter_dir_files(RETROS_DIR)

    marker_counts: dict[str, int] = {}
    with_connections = 0
    for label, path in blocks:
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        for c in _marker_components(text):
            marker_counts[c] = marker_counts.get(c, 0) + 1
        if extract_section(path, ("Connections", "Conexiones")):
            with_connections += 1

    print("Corpus totals")
    print(f"  blocks : {len(blocks)}")
    print(f"  docs   : {len(docs)}")
    print(f"  retros : {len(retros)}")
    print(f"  focuses: {len(available_focuses())}")
    print(f"  blocks with a Connections section: {with_connections}")

    print("\nEvidence markers (occurrences across blocks)")
    # Sort by count desc, then name asc for determinism.
    for marker in sorted(marker_counts, key=lambda m: (-marker_counts[m], m)):
        print(f"  {marker:<18} {marker_counts[marker]:>6}")
    return 0


